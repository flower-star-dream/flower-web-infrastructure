-- =====================================================================
-- Outbox 增量脚本配套 DML（示例）（规范 §13.2：DDL 变更必须配套说明 DML 影响）
-- @Author: 花海
-- @Date: 2026/08/15 10:00
-- @Description: 示例增量 DML（db/versions/）：新增 nullable 列本身无需数据迁移，
--               本脚本为一次性存量数据修正示例（幂等）——将历史待发送消息的
--               next_retry_at 初始化为当前时间（等价于立即可参与下次轮询投递）。
-- 配套规则：纯加列（nullable/带默认值）且不改变存量语义时，DML 可为空，但必须在
--           变更说明中声明"无数据迁移"；涉及存量数据语义变更（回填/清洗/转换）
--           必须提供可重复执行的幂等 DML（带 WHERE 过滤已完成处理的行）。
-- =====================================================================

UPDATE message_outbox
SET next_retry_at = NOW()
WHERE status = 0            -- 仅待发送消息
  AND next_retry_at IS NULL -- 幂等：已初始化的行不重复处理
;
